import Employee from '../module/Employee.module.js';
import UserModule from '../module/User.module.js';
import bcrypt from 'bcrypt';

// get all employees

// get /api/employees
const getAllEmployees = async (req, res) => {
  try {
    const { department } = req.query;
    const where = {};

    // Fix for "All Departments" string or empty values sent from frontend
    if (department && department !== 'All Departments' && department.trim() !== '') {
      where.department = department;
    }

    // 1. FIXED: Native MongoDB sorting & clean promise resolution chaining
    const employees = await Employee.find(where)
      .sort({ createdAt: -1 })
      .populate('userId', 'email role')
      .lean();

    // 2. FIXED: Removed unnecessary "await" from array.map()
    const result = employees.map((employee) => {
      return {
        ...employee,
        id: employee._id ? employee._id.toString() : null,
        user: employee.userId
          ? {
              email: employee.userId.email,
              role: employee.userId.role,
            }
          : null,
      };
    });

    return res.status(200).json(result);
  } catch (error) {
    // 3. FIXED: Flipped positions so errors log before the request terminates
    console.error('Error in getAllEmployees:', error);
    return res.status(500).json({ message: error.message });
  }
};

// create a new employee
// post /api/employees
const createEmployee = async (req, res) => {
  try {
    // 1. Added role to destructuring (userId is generated by MongoDB, so no need to require it from req.body)
    const {
      firstName,
      lastName,
      email,
      phone,
      department,
      position,
      basicSalary,
      allowances,
      deductions,
      joiningDate,
      bio,
      password,
      role,
    } = req.body;

    // 2. Removed !userId check since the DB creates the ID
    if (!firstName || !lastName || !email || !phone || !department || !position || !password) {
      return res.status(400).json({ message: 'Missing required fields' });
    }
    const existingUser = await UserModule.findOne({ email });
    if (existingUser) {
      return res
        .status(409)
        .json({ message: 'An account with this email address already exists.' });
    }

    const hashedPassword = await bcrypt.hash(password, 10);

    const user = await UserModule.create({
      email,
      password: hashedPassword,
      role: role.toLowerCase() || 'employee',
    });

    // 3. Removed the incorrect 'new' keyword before Employee.create
    const newEmployee = await Employee.create({
      userId: user._id,
      firstName,
      lastName,
      email,
      phone,
      department: department || 'Engineering',
      position,
      basicSalary: Number(basicSalary) || 0,
      allowances: Number(allowances) || 0,
      deductions: Number(deductions) || 0,
      // 4. Fixed Date fallback fallback logic
      joiningDate: joiningDate ? new Date(joiningDate) : new Date(),
      bio: bio || '',
    });

    return res.status(201).json(newEmployee);
  } catch (error) {
    // 5. Moved console.log above the return statement so it actually executes
    console.error(error);
    return res.status(500).json({ message: error.message });
  }
};

// update an employee
// put /api/employees/:id
const updateEmployee = async (req, res) => {
  try {
    const { id } = req.params;
    const {
      firstName,
      lastName,
      email,
      phone,
      department,
      position,
      basicSalary,
      allowances,
      deductions,
      employmentStatus,
      bio,
      password,
      role,
    } = req.body;

    console.log(req.body, id);

    if (!id || !firstName || !lastName || !email || !phone || !department || !position) {
      return res.status(400).json({ message: 'Missing required fields' });
    }
    // Check if the userId already exists in the Employee collection
    const existingEmployee = await Employee.findById(id);
    if (!existingEmployee) {
      return res.status(400).json({ message: 'Employee with this user ID already exists' });
    }

    const newEmployee = await Employee.findByIdAndUpdate(id, {
      firstName,
      lastName,
      email,
      phone,
      position,
      department: department || 'Engineering',
      basicSalary: Number(basicSalary) || 0,
      allowances: Number(allowances) || 0,
      deductions: Number(deductions) || 0,
      employmentStatus: employmentStatus || 'active',
      isDeleted: false,
      bio: bio || '',
    });
    // update the user's email and password in the User collection
    const userUpdateData = { email };
    if (role) userUpdateData.role = role;
    if (password) userUpdateData.password = await bcrypt.hash(password, 10);
    await UserModule.findByIdAndUpdate(existingEmployee._id, userUpdateData);

    return res.status(201).json(newEmployee);
  } catch (error) {
    console.log(error);

    return res.status(500).json({ message: error.message });
  }
};

// Delete an employee
// delete /api/employees/:id
const deleteEmployee = async (req, res) => {
  try {
    const { id } = req.params;
    const employee = await Employee.findById(id);
    if (!employee) {
      return res.status(404).json({ message: 'Employee not found' });
    }

    employee.isDeleted = true;
    employee.employmentStatus = 'INACTIVE'; // Optionally set employment status to INACTIVE
    await employee.save();
    return res.status(200).json({ message: 'Employee deleted successfully' });
  } catch (error) {
    return res.status(500).json({ message: error.message });
  }
};

export { getAllEmployees, createEmployee, updateEmployee, deleteEmployee };
